/*
 * Visitor tracking: Google Analytics 4 + Meta (Facebook) Pixel.
 * Does nothing until the IDs below are filled in.
 *   GA4 ID looks like:   G-XXXXXXXXXX   (Google Analytics > Admin > Data streams)
 *   Pixel ID looks like: 123456789012345 (Meta Events Manager > Data sources)
 * quote-form.js sends a "generate_lead" (GA) and "Lead" (Pixel) event on each form submission.
 */
(function () {
  var GA_ID = "";
  var PIXEL_ID = "";

  if (GA_ID) {
    var s = document.createElement("script");
    s.async = true;
    s.src = "https://www.googletagmanager.com/gtag/js?id=" + GA_ID;
    document.head.appendChild(s);
    window.dataLayer = window.dataLayer || [];
    window.gtag = function () { window.dataLayer.push(arguments); };
    window.gtag("js", new Date());
    window.gtag("config", GA_ID);
  }

  if (PIXEL_ID) {
    !function (f, b, e, v, n, t, s) {
      if (f.fbq) return; n = f.fbq = function () { n.callMethod ? n.callMethod.apply(n, arguments) : n.queue.push(arguments); };
      if (!f._fbq) f._fbq = n; n.push = n; n.loaded = !0; n.version = "2.0"; n.queue = [];
      t = b.createElement(e); t.async = !0; t.src = v; s = b.getElementsByTagName(e)[0]; s.parentNode.insertBefore(t, s);
    }(window, document, "script", "https://connect.facebook.net/en_US/fbevents.js");
    window.fbq("init", PIXEL_ID);
    window.fbq("track", "PageView");
  }
})();
